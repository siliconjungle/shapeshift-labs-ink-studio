const fs = require('node:fs');
const path = require('node:path');
const { commandReference } = require('./reference-cli.js');
const { publicApis } = require('./reference-api.js');
const { headingId, loadGuides } = require('./reference-guides.js');
const { checkLinks } = require('./reference-links.js');

const root = path.resolve(__dirname, '..');
const destination = 'docs/reference';
const generated = '<!-- Generated by npm run docs:build. Edit the source or guide linked below. -->';
const code = value => {
  const text = String(value).replace(/\r?\n\s*/g, ' ');
  const fence = text.includes('`') ? '``' : '`';
  return fence + text.replaceAll('|', '\\|') + fence;
};
const slug = value => value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const compare = (a, b) => a < b ? -1 : a > b ? 1 : 0;
const unique = values => [...new Set(values)];
const fromReference = link => path.posix.relative(destination, link);

function groupBy(items, key) {
  const groups = new Map();
  for (const item of items) {
    const group = key(item);
    if (!groups.has(group)) groups.set(group, []);
    groups.get(group).push(item);
  }
  return new Map([...groups].sort(([a], [b]) => compare(a, b)));
}

function graphPort(name, port, direction) {
  const detail = [
    port.unit, port.description, port.quantity && JSON.stringify(port.quantity),
    Object.keys(port.constraints).length ? JSON.stringify(port.constraints) : '',
    port.properties && JSON.stringify(port.properties)
  ].filter(Boolean).join(' · ');
  return '| ' + direction + ' | ' + code(name) + ' | ' + code(port.type) + ' | ' +
    (Object.hasOwn(port, 'default') ? code(JSON.stringify(port.default)) : port.required ? 'Required' : '—') + ' | ' +
    detail.replaceAll('|', '\\|').replace(/\r?\n/g, ' ') + ' |';
}

function graphSection(node, guides, command) {
  const lines = ['### ' + node.id, '', node.description ?? '', '', 'Origin: ' + node.origin + '.',
    ...(node.timeDependent ? ['Samples the graph clock.'] : []),
    ...(node.specialization ? [node.specialization.description] : []), ''];
  if (node.inputs || node.outputs) {
    const ports = [ ...Object.entries(node.inputs ?? {}).map(([name, port]) => graphPort(name, port, 'Input')),
      ...Object.entries(node.outputs ?? {}).map(([name, port]) => graphPort(name, port, 'Output')) ];
    if (ports.length) lines.push('| Direction | Port | Type | Default | Details |', '| --- | --- | --- | --- | --- |', ...ports, '');
  }
  for (const constraint of node.constraints) lines.push('- ' + constraint);
  if (node.constraints.length) lines.push('');
  if (guides.length) lines.push('Guides: ' + guides.map(link => '[guide](' + fromReference(link) + ')').join(', '), '');
  if (command === 'graph' && node.example) {
    const file = node.example.kind === 'node' ? 'example.cjs' : 'example.json';
    lines.push('Get the runnable example with ' + code('ink-studio ' + command + ' describe ' + node.id + ' --example > ' + file) + '.',
      'Run it with ' + code((node.example.kind === 'node' ? 'node ' : 'ink-studio graph run ') + file) + '.', '');
  } else {
    lines.push('Run this operation with the patch runner. See the [patch example](../patch-tooling.md#run-night-current).', '');
  }
  return lines.join('\n');
}

function apiDescription(row) {
  switch (row.kind) {
    case 'function': case 'class':
      return row.parameters ?? (row.arity ? '(' + row.arity + ' required parameters)' : '()');
    case 'alias': return 'Alias of ' + row.target;
    case 'registry': return 'Operation registry. See the graph reference.';
    case 'value': return Object.hasOwn(row, 'value') ? row.type + ' = ' + JSON.stringify(row.value) : row.type;
    case 'accessor': return [row.read ? 'get' : '', row.write ? 'set' : ''].filter(Boolean).join(' / ');
    default: return '';
  }
}

function markdownApiRow(row, guides) {
  const links = guides.map(guide => '[guide](' + fromReference(guide) + ')').join(', ');
  const description = apiDescription(row);
  const source = row.source ? '[source](' + fromReference(row.source) + ')' : '';
  return '| ' + code(row.id) + ' | ' + row.kind + ' | ' + (description ? code(description) : '') + ' | ' +
    [links, source].filter(Boolean).join(', ') + ' |';
}

const letterGroup = value => {
  const initial = value.toLowerCase().charAt(0);
  if (initial < 'g') return 'a-f';
  if (initial < 'k') return 'g-j';
  if (initial < 'n') return 'k-m';
  if (initial < 't') return 'n-s';
  return 't-z';
};

async function generate() {
  const studio = require('..');
  process.env.INK_STUDIO_DEVELOPMENT = '1';
  const toolkit = studio.load();
  const guideIndex = loadGuides(root);
  const cli = commandReference(root);
  const api = await publicApis(root, studio, toolkit);
  const graph = studio.listGraphNodes({ kit: toolkit });
  const patchOperations = require('../cli/patch-nodes.js').patchNodes(toolkit);
  const patch = studio.listGraphNodes({ kit: toolkit, operations: patchOperations }).nodes.filter(node =>
    Object.hasOwn(patchOperations, node.id));
  const catalog = JSON.parse(fs.readFileSync(path.join(root, 'catalog.json'), 'utf8'));

  const results = new Map();
  const entries = [];
  const apiPages = [];
  const graphPages = [];
  const addPage = (name, title, parts) => results.set(name + '.md', [generated, '', '# ' + title, '', ...parts].join('\n').trimEnd() + '\n');
  const reference = (file, anchor) => destination + '/' + file + '.md' + (anchor ? '#' + headingId(anchor) : '');
  const guidesFor = (id, family, source) => {
    const topic = source && 'docs/' + path.basename(source, path.extname(source)) + '.md';
    return unique([...guideIndex.docsFor(id), ...(family ? guideIndex.docsFor(family) : []),
      ...(guideIndex.documents.has(topic) ? [topic] : [])]).slice(0, 5);
  };

  addPage('cli', 'Command-line reference', [
    'The command signatures below come from the running Ink Studio CLI. Use `ink-studio help` for the same usage text in the terminal.',
    '', '## Usage', '', '```text', ...cli.lines, '```', '',
    '## Registered subcommands', '',
    'These entries are checked against their command dispatchers. Where a dispatcher declares its accepted options, those appear alongside the command.',
    '', ...cli.subcommands.map(({ name, source, flags }) =>
      '- ' + code('ink-studio ' + name) + (flags?.length ? ' · ' + flags.map(flag => code('--' + flag)).join(', ') : '') +
      ' · [source](' + fromReference(source) + ')'),
    '',
    '## Additional option references', '',
    'These options are read by CLI code. Follow each source link for the accepted values and command context.',
    '', ...cli.additionalFlags.map(([name, origins]) =>
      '- ' + code('--' + name) + ' · ' + origins.map(file => '[' + file + '](' + fromReference(file) + ')').join(', '))
  ]);
  for (const [name, usages] of cli.commands) {
    const docs = [reference('cli', 'usage')];
    entries.push({ id: 'ink-studio ' + name, kind: 'command', title: name, use: usages.join('\n'), docs });
    for (const use of usages) {
      if (use === name) continue;
      entries.push({ id: 'ink-studio ' + use.split(/ {2,}/)[0], kind: 'usage', title: name, use, docs });
    }
  }
  for (const { name, source, usages, flags } of cli.subcommands) {
    entries.push({ id: 'ink-studio ' + name, kind: 'subcommand', title: name, use: usages.join('\n'),
      ...(flags && { flags }), source, docs: [reference('cli', 'registered subcommands')] });
  }
  for (const [name, origins] of cli.additionalFlags) {
    entries.push({ id: '--' + name, kind: 'option', docs: [reference('cli', 'additional option references'), ...origins] });
  }

  for (const [surface, rows] of api) {
    if (!(rows instanceof Map)) {
      const title = surface === 'node' ? 'Node package' : surface === 'toolkit' ? 'Loaded toolkit and bundle' : surface;
      publishApi('api-' + slug(surface), title, new Map([[surface, rows]]));
      continue;
    }
    const pages = new Map();
    for (const [family, items] of rows) {
      const base = 'api-' + slug(surface);
      for (const row of items) {
        const page = family === 'procedural' || family === 'world'
          ? base + '-' + family + '-' + letterGroup(row.family.split('.').at(-1))
          : base + '-' + letterGroup(family);
        if (!pages.has(page)) pages.set(page, []);
        pages.get(page).push(row);
      }
    }
    for (const [page, contents] of [...pages].sort(([a], [b]) => compare(a, b))) {
      publishApi(page, surface + ' · ' + page.slice('api-kit-'.length), groupBy(contents, row => row.family));
    }
  }

  function publishApi(page, title, groups) {
    const body = [
      'Members and callable signatures come from the public entry point. Guide links point to examples and context where available.',
      ''
    ];
    for (const [family, rows] of groups) {
      body.push('## ' + family, '', '| Member | Kind | Signature or value | Guides and source |', '| --- | --- | --- | --- |');
      for (const row of rows) {
        const guides = unique([...(row.guide ? [row.guide] : []), ...guidesFor(row.id, row.family, row.source)]);
        body.push(markdownApiRow(row, guides));
        const { id, kind, parameters, arity, source, type, value, target, read, write } = row;
        entries.push({ id, kind: 'api', apiKind: kind, parameters, arity, source, type, value, target, read, write,
          ...(!parameters && { use: apiDescription(row) }),
          docs: [reference(page, family), ...guides] });
      }
      body.push('');
    }
    addPage(page, title, body);
    apiPages.push('- [' + title + '](' + page + '.md)');
  }

  const graphRecords = [
    ...graph.nodes.map(node => ({ node, command: 'graph', category: node.category })),
    ...patch.map(node => ({ node, command: 'patch', category: 'patch' }))
  ];
  for (const [category, nodes] of groupBy(graphRecords, row => row.category)) {
    const page = 'graph-' + slug(category);
    const sections = nodes.map(({ node, command }) => {
      if (command === 'graph' && !node.example) throw new Error('Graph operation missing a runnable example: ' + node.id);
      const guides = unique([...guidesFor(node.id), ...(command === 'patch' ? ['docs/patch-tooling.md'] : [])]);
      const { id, description, inputs, outputs } = node;
      const use = 'ink-studio ' + command + ' describe ' + id + ' --json';
      const keywords = [...Object.keys(inputs ?? {}), ...Object.keys(outputs ?? {}), category].join(' ');
      entries.push({ id, kind: command === 'patch' ? 'patch-node' : 'graph', ...(description && { summary: description }), use, keywords,
        docs: [reference(page, id), ...guides] });
      return graphSection(node, guides, command);
    });
    addPage(page, 'Graph operations · ' + category, [
      'Ports, defaults, and constraints come from the registered operations. Use ' +
        code((category === 'patch' ? 'patch' : 'graph') + ' describe <op> --json') + ' for the full structured record.',
      '', ...sections
    ]);
    graphPages.push('- [' + category + '](' + page + '.md)');
  }

  for (const item of catalog.entries) {
    entries.push({ id: item.id, kind: 'feature', title: item.title, summary: item.what, use: item.use,
      keywords: item.tags.join(' '), docs: ['catalog.json', ...(item.where ?? '').split(', ')
        .map(file => file.trim()).filter(file => file && fs.existsSync(path.join(root, file)))] });
  }

  entries.push(...guideIndex.guides);
  addPage('guides', 'Guide index', ['All checked-in guides, indexed by title and section headings.', '',
    ...guideIndex.guides.map(item => '- [' + item.title + '](' + fromReference(item.id) + ')')]);

  addPage('index', 'Ink Studio public reference', [
    'Search this reference with `ink-studio catalog <words> --all`. Add `--full` for details or `--json` for structured results.',
    'The keyword search includes the curated features, CLI usages, public API members, graph operations, and the full text of the guides.',
    '', '- [Command-line reference](cli.md)', '- [Guide index](guides.md)', '- [Machine-readable search index](index.json)',
    '', '## Public APIs', '', ...apiPages, '', '## Graph operations', '', ...graphPages
  ]);
  const sorted = entries.sort((a, b) => compare(a.id, b.id) || compare(a.kind, b.kind) || compare(a.use ?? '', b.use ?? ''));
  results.set('index.json', '{\n  "format": "ink-studio/public-reference",\n  "version": 1,\n  "entries": [\n' +
    sorted.map(entry => '    ' + JSON.stringify(entry)).join(',\n') + '\n  ]\n}\n');
  checkLinks(root, guideIndex.documents.keys(), new Map([...results].map(([file, content]) =>
    [destination + '/' + file, content])), sorted);
  return results;
}

function differences(directory, output) {
  const existing = fs.existsSync(directory) ? fs.readdirSync(directory, { withFileTypes: true }) : [];
  return {
    extra: existing.filter(file => !output.has(file.name)).map(file => file.name),
    changed: [...output].filter(([file, content]) => {
      const target = path.join(directory, file);
      const stat = fs.statSync(target, { throwIfNoEntry: false });
      return !stat?.isFile() || fs.readFileSync(target, 'utf8') !== content;
    })
  };
}

async function main(args) {
  if (args.some(argument => !['--check', '--quiet'].includes(argument)) || new Set(args).size !== args.length)
    throw new TypeError('Use npm run docs:build or npm run docs:check');
  const check = args.includes('--check');
  const directory = path.join(root, destination);
  const output = await generate();
  const { changed, extra } = differences(directory, output);
  if (check) {
    if (changed.length || extra.length) throw new Error('Public reference is out of date. Run npm run docs:build and commit the result.\n' +
      [...changed.map(([file]) => '  Missing or changed: ' + file), ...extra.map(file => '  Extra: ' + file)].join('\n'));
  } else {
    for (const file of extra) {
      const target = path.join(directory, file);
      if (!fs.lstatSync(target).isFile() || !fs.readFileSync(target, 'utf8').startsWith(generated))
        throw new Error('Move the hand-written reference file out of ' + destination + ': ' + file);
    }
    fs.mkdirSync(directory, { recursive: true });
    for (const [file, content] of changed) fs.writeFileSync(path.join(directory, file), content);
    for (const file of extra) fs.unlinkSync(path.join(directory, file));
  }
  if (!args.includes('--quiet'))
    console.log((check ? 'Verified' : 'Generated') + ' ' + output.size + ' public reference files.');
}

if (require.main === module) main(process.argv.slice(2)).catch(error => {
  console.error(error.message);
  process.exitCode = 1;
});

module.exports = { generate, differences };
