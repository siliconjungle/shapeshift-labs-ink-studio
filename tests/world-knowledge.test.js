const assert = require('node:assert/strict');
const path = require('node:path');
const {test} = require('node:test');
const {load} = require('..');
const {embedStoryDocuments} = require('../cli/story-document.js');
const W = load().KIT.world;
const R = W.runtime;
const file = '../examples/story-documents/lock-knowledge.world.json';
const relay = require('../examples/story-documents/lock-knowledge.relay.actions.json');
const copy = value=>JSON.parse(JSON.stringify(value));
const source = ()=>embedStoryDocuments(copy(require(file)),path.resolve(__dirname,file));
const actor = id=>({kind:'actor',id});
const mira = actor('crew/mira'), niko = actor('crew/niko'), dispatcher = actor('crew/dispatcher');
const watch = {kind:'faction',id:'harbor-watch'}, fact = '1.0', story = 'lock-knowledge/repair-brief';
const query = (run,field,args)=>run.query().probe(field,undefined,args).value;
const knowledge = (run,holder)=>query(run,'world/knowledge',{holder,fact});
const lineage = (run,holder,field,limit)=>run.query().trace('world/knowledge',undefined,{holder,fact,field,limit}).value;
const causal = (run,event)=>run.query().trace('world/cause',undefined,{event}).value;
const restore = saved=>R.create(saved.world,{checkpoint:copy(saved)});
const share = (tick,from,to,fields)=>({tick,action:'world/share-fact',args:{fact,from,to,...(fields&&{fields})}});

test('witnesses hold only observed details while an unbriefed holder is unknown',()=>{
  const world = source(), run = R.create(world);
  assert.deepEqual(R.storyPreflight(world).knowledge.fields['lock-damage'],['at','subject/structure','data/lanes','data/severity']);
  run.advance(1);
  const full = knowledge(run,mira), partial = knowledge(run,niko), unknown = knowledge(run,watch);
  assert.equal(full.status,'complete');
  assert.equal(full.knowledge.origin,'witness');
  assert.deepEqual(full.knowledge.data,{lanes:2,severity:'critical'});
  assert.equal(partial.status,'partial');
  assert.deepEqual(partial.knowledge.at,{place:'harbor/lock',point:[2,0,5]});
  assert.deepEqual(partial.knowledge.data,{});
  assert.deepEqual(partial.knowledge.subjects,{});
  assert.deepEqual(partial.knowledge.missing,['subject/structure','data/lanes','data/severity']);
  assert.equal(unknown.status,'unknown');
  assert.equal(unknown.knowledge,undefined);
  assert.deepEqual(query(run,'world/knowledge',{fact}).records.map(row=>row.holder),[mira,niko]);
  const witnessTrace = lineage(run,mira,'at');
  assert.equal(witnessTrace.steps[0].via,fact);
  assert(causal(run,'1.1').nodes.some(row=>row.event===fact&&row.kind==='world-fact'));
  assert.deepEqual(run.history,[]);
});

test('missing details block reports and readiness until the faction receives the needed fields',()=>{
  const run = R.create(source());
  run.schedule(copy(relay));
  run.advance(2);
  assert.equal(knowledge(run,watch).knowledge.origin,'secondhand');
  assert.deepEqual(knowledge(run,watch).knowledge.data,{});
  const queued = run.checkpoint().incidentCandidateState[story];
  assert.equal(queued.status,'blocked');
  assert.equal(queued.report.checks['severity-reported'].reason,'query-value-unavailable');
  run.advance(3);
  const failed = run.events.find(row=>row.kind==='fact-report-rejected');
  assert.equal(failed.reason,'source-lacks-details');
  assert.deepEqual(failed.missing,['data/severity']);
  assert.equal(knowledge(run,dispatcher).status,'unknown');
  const resumed = restore(run.checkpoint());
  run.advance(4);
  assert.equal(query(run,'world/story-lifecycle')[story].status,'active');
  assert.equal(knowledge(run,watch).status,'partial');
  assert.equal(knowledge(run,watch).knowledge.data.severity,'critical');
  assert.equal(knowledge(run,watch).knowledge.data.lanes,undefined);
  resumed.advance(9);
  run.advance(9);
  assert.equal(knowledge(run,watch).status,'complete');
  const brief = query(run,'world/story-lifecycle')[story];
  assert.equal(brief.status,'completed');
  assert.equal(brief.flow.route[0].objectives['lane-count'].tick,7);
  assert.deepEqual(resumed.checkpoint(),run.checkpoint());
  assert.deepEqual(R.replay(copy(run.recording())).checkpoint(),run.checkpoint());
});

test('secondhand reports track each detail through its own source and preserve firsthand receipts',()=>{
  const run = R.create(source());
  run.schedule(copy(relay));
  run.advance(6);
  const recipient = knowledge(run,dispatcher).knowledge, mixed = knowledge(run,niko).knowledge;
  assert.equal(recipient.origin,'secondhand');
  assert.deepEqual(recipient.data,{severity:'critical'});
  assert.equal(recipient.receipts.at.via,'2.0');
  assert.equal(recipient.receipts['data/severity'].via,'4.0');
  assert.deepEqual(recipient.receipts['data/severity'].from,watch);
  assert.equal(mixed.origin,'mixed');
  assert.equal(mixed.receipts.at.mode,'witness');
  assert.equal(mixed.receipts['data/severity'].mode,'report');
  const trace = lineage(run,niko,'data/severity');
  assert.deepEqual(trace.steps.map(row=>row.holder),[niko,dispatcher,watch,mira]);
  assert.equal(trace.value,'critical');
  assert.equal(trace.status,'complete');
  assert.equal(lineage(run,niko,'data/severity',2).gap.reason,'limit');
  assert(causal(run,'5.0').nodes.some(row=>row.event==='4.0'&&row.kind==='fact-learned'));
  run.schedule([share(7,watch,dispatcher,['at'])]);
  run.advance(7);
  assert.equal(knowledge(run,dispatcher).knowledge.receipts.at.event,'5.0');
});

test('knowledge outlives fact eviction and flags missing knowledge links after its own retention',()=>{
  const world = source();
  world.facts.limit = 1;
  const run = R.create(world), runner = actor('crew/runner');
  run.schedule([...copy(relay),share(9,watch,runner,['data/lanes'])]);
  run.advance(9);
  assert.equal(query(run,'world/facts',{id:fact}).matched,0);
  assert.equal(knowledge(run,runner).knowledge.data.lanes,2);
  assert.deepEqual(lineage(run,runner,'data/lanes').steps.map(row=>row.holder),[runner,watch,mira]);
  assert.deepEqual(restore(run.checkpoint()).checkpoint(),run.checkpoint());

  const sparse = source();
  sparse.knowledge.limit = 1;
  sparse.commands[0].args.witnesses = [{holder:mira}];
  const small = R.create(sparse);
  small.advance(3);
  assert.equal(knowledge(small,mira).status,'unknown');
  assert.equal(knowledge(small,watch).dropped,1);
  assert.equal(lineage(small,watch,'at').gap.reason,'knowledge-retention');
  assert.deepEqual(restore(small.checkpoint()).checkpoint(),small.checkpoint());
});

test('schema validation rejects fabricated witnesses and checkpoint provenance',()=>{
  const world = source();
  const witness = world.commands[0].args.witnesses[1];
  witness.fields = ['data/absent'];
  assert.throws(()=>R.create(world),/Invalid witness or observed fields/);
  witness.fields = ['at'];
  witness.holder = mira;
  assert.throws(()=>R.create(world),/Duplicate world fact witness/);
  witness.holder = niko;
  assert.throws(()=>R.create({knowledge:true}),/World knowledge requires typed world facts/);
  const disabled = source();
  delete disabled.knowledge;
  delete disabled.storyDocuments;
  assert.throws(()=>R.create(disabled),/Enable world knowledge to record fact witnesses/);
  const run = R.create(world);
  assert.throws(()=>run.schedule([share(2,mira,mira)]),/two distinct holders/);
  assert.throws(()=>run.schedule([{tick:2,action:'world/event',args:{kind:'fact-learned'}}]),/to record learning/);
  run.schedule([share(2,dispatcher,niko,['data/lanes']),...copy(relay)]);
  run.advance(2);
  assert(run.events.some(row=>row.kind==='fact-report-rejected'&&row.reason==='source-unaware'));
  run.advance(9);
  const bad = copy(run.checkpoint());
  const row = bad.knowledgeState.records.find(row=>row.holder.id===dispatcher.id);
  row.details['data/severity'].via = '1.1';
  assert.throws(()=>restore(bad),/Invalid saved knowledge report source/);
  row.details['data/severity'].via = '4.0';
  row.details['data/severity'].value = 'different';
  assert.throws(()=>restore(bad),/Invalid saved knowledge record/);
});
